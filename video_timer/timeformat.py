"""Выражения времени для фильтра `drawtext` в ffmpeg.

Модуль отвечает за две вещи: как посчитать значение таймера выражением
ffmpeg и как получить такой же текст в Python — для проверок, документации
и тестов. Зависимости: `config` ради `VideoTimerError`; сам `config` этот
модуль не импортирует, обратных импортов нет.

Инвариант модуля: двоеточия и запятые в значении `text=` экранируются, иначе
ffmpeg разбирает выражение как список аргументов фильтра и падает. Число
обратных слэшей разное: двоеточие требует двух (`\\\\:`), запятая — одного
(`\\,`) — потому что значение `text=` разбирается дважды, фильтром и `drawtext`.
Точные правила и их проверка на ffmpeg описаны в :func:`_escape`.
"""

from __future__ import annotations

from video_timer.config import VideoTimerError

# since: v0.1 (FR-04), остальные форматы — v0.2
FORMATS: tuple[str, ...] = ("mmss", "hhmmss", "mmssms")
"""Поддерживаемые форматы часов.

В v0.1 доступен только ``mmss`` (``мм:сс``). Значения ``hhmmss`` и
``mmssms`` входят в v0.2 (FR-04).
"""


def _escape(raw: str) -> str:
    """Экранировать символы, которые ffmpeg считает разделителями фильтра.

    Спека: FR-04, инвариант из `SPEC.md` 7.3. Версия: v0.1.

    Значение `text=` разбирается дважды: сначала парсер `-filter_complex`,
    который делит цепочку на фильтры по запятой, затем сам `drawtext`, который
    делит свои аргументы по двоеточию. Отсюда разное число слэшей:

        ``:`` → ``\\\\:`` (два слэша) — иначе ffmpeg обрывает аргумент и ищет
            следующий фильтр;
        ``,`` → ``\\,`` (один слэш) — второй уровень запятые не разделяет;
        ``\\`` → ``\\\\`` (два слэша) — свой символ, чтобы буквальный слэш не
            съел следующий символ.

    Проверено на ffmpeg 7.1: результат попиксельно совпадает с тем же текстом,
    переданным через `textfile`, иначе ffmpeg отказывается разбирать фильтр.

    Обратный слэш экранируется первым: добавленные при этом слэши уже
    экранированы и повторно не обрабатываются.

    Args:
        raw: «сырая» строка, где двоеточие может быть временным разделителем.

    Returns:
        Строку, безопасную для вставки в значение `text=`. Повторный вызов
            на её результате даст лишние слэши — экранировать нужно исходный
            текст.

    Raises:
        Не бросает исключений.

    Пример:
        _escape("00:05")
        # "00\\\\:05"
        _escape("01:02, готово")
        # "01\\\\:02\\, готово"
    """
    return raw.replace("\\", "\\\\").replace(":", "\\\\:").replace(",", "\\,")


# since: v0.1 (FR-01, FR-02, FR-04)
def clock_expression(value_expr: str, fmt: str) -> str:
    """Собрать выражение ffmpeg, печатающее значение таймера.

    Спека: FR-01, FR-02, FR-03, FR-04. Версия: v0.1 (``mmss``), v0.2
    (``hhmmss``, ``mmssms``).

    На вход подаётся готовое числовое выражение ffmpeg — например, время
    кадра `t`, или `N-t` для обратного отсчёта (FR-02). Форматирование,
    округление и вычитание делаются внутри через целочисленную арифметику
    ffmpeg `floor`, чтобы на девятой секунде показывалось `00:01`, а не
    `00:00` (критерий A1).

    Секунды отрицательного значения не показываются: для countdown значение
    обрезается нулём на уровне выражения, а фаза hold (FR-03) добавляется
    отдельным фильтром в `filters.FilterBuilder.build_timer_filters()`.

    Инвариант: результат возвращается уже экранированным через
    :func:`_escape`, двоеточия внутри текста записаны как `\\\\:`.

    Args:
        value_expr: числовое выражение ffmpeg со значением таймера в секундах.
        fmt: формат из :data:`FORMATS`.

    Returns:
        Строку-выражение для `drawtext=text=...`, уже экранированную.

    Raises:
        VideoTimerError: `fmt: неизвестный формат часов` — если `fmt` не из
            :data:`FORMATS`; в v0.1 дополнительно принимается только `mmss`.

    Пример:
        clock_expression("t", "mmss")
        # "<выражение, печатающее 00:05 при t=5>"
    """
    if fmt != "mmss":
        raise VideoTimerError(
            f"fmt: формат {fmt} доступен с версии 0.2, в 0.1 только mmss"
        )

    value = f"max(0,{value_expr})"
    minutes = f"floor({value}/60)"
    seconds = f"{value}-60*{minutes}"
    raw = f"%{{eif:{minutes}:d:2}}:%{{eif:{seconds}:d:2}}"
    return _escape(raw)


# since: v0.1 (FR-03)
def _escape_enable(expression: str) -> str:
    """Экранировать запятые в выражении `enable=`.

    Спека: FR-03, инвариант из `SPEC.md` 7.3. Версия: v0.1.

    Значение `enable=` разбирает только парсер `-filter_complex`, второй
    разбор внутри `drawtext` его не трогает, поэтому запятые в выражениях
    вида ``between(t,10,15)`` экранируются одним обратным слэшем.

    Args:
        expression: выражение из чисел, запятых и функций ffmpeg.

    Returns:
        Строку, безопасную для вставки в значение `enable=`.

    Raises:
        Не бросает исключений.

    Пример:
        _escape_enable("between(t,10,15)")
        # "between(t\\,10\\,15)"
    """
    return expression.replace("\\", "\\\\").replace(",", "\\,")


# since: v0.1 (FR-04)
def static_clock_text(fmt: str) -> str:
    """Вернуть образец текста часов в заданном формате.

    Спека: FR-04. Версия: v0.1 (``mmss``), v0.2 (остальные форматы).

    Нужен там, где значение времени вычислить нельзя: подпись в GUI,
    ожидаемый кадр в тестах приёмки (A1, A2), текст в README.

    Args:
        fmt: формат из :data:`FORMATS`.

    Returns:
        Пример строки с нулями на месте цифр: ``00:00`` для ``mmss``.

    Raises:
        VideoTimerError: `fmt: неизвестный формат часов` — если формат не из
            :data:`FORMATS` или он доступен только в более поздней версии.

    Пример:
        static_clock_text("mmss")
        # "00:00"
    """
    if fmt != "mmss":
        raise VideoTimerError(
            f"fmt: формат {fmt} доступен с версии 0.2, в 0.1 только mmss"
        )
    return "00:00"
