"""Выражения времени для фильтра `drawtext` в ffmpeg.

Модуль отвечает за две вещи: как посчитать значение таймера выражением
ffmpeg и как получить такой же текст в Python — для проверок, документации
и тестов. Зависимости: только стандартная библиотека, импортируется
`filters` и `renderer`, сам ничего не импортирует из пакета.

Инвариант модуля: двоеточия и запятые в значении `text=` экранируются
(`\\:`, `\\,`), иначе ffmpeg разбирает выражение как список аргументов
фильтра и падает. Экранирование выполняет :func:`_escape`.
"""

from __future__ import annotations

# since: v0.1 (FR-04), остальные форматы — v0.2
FORMATS: tuple[str, ...] = ("mmss", "hhmmss", "mmssms")
"""Поддерживаемые форматы часов.

В v0.1 доступен только ``mmss`` (``мм:сс``). Значения ``hhmmss`` и
``mmssms`` входят в v0.2 (FR-04).
"""


def _escape(raw: str) -> str:
    """Экранировать символы, которые ffmpeg считает разделителями фильтра.

    Спека: FR-04, инвариант из `SPEC.md` 7.3. Версия: v0.1.

    Внутри значения `text=` двоеточие отделяет время включения, а запятая —
    аргументы фильтра, поэтому оба символа заменяются на экранированные.
    Обратный слэш экранируется первым, чтобы не получить двойное экранирование.

    Args:
        raw: строка, в которой двоеточие может быть временным разделителем.

    Returns:
        Строку, безопасную для вставки в значение `text=`.

    Пример:
        _escape("00:05")
        # "00\\\\:05"
    """
    raise NotImplementedError


# since: v0.1 (FR-01, FR-02, FR-04)
def clock_expression(value_expr: str, fmt: str) -> str:
    """Собрать выражение ffmpeg, печатающее значение таймера.

    Спека: FR-01, FR-02, FR-03, FR-04. Версия: v0.1 (``mmss``), v0.2
    (``hhmmss``, ``mmssms``).

    На вход подаётся готовое числовое выражение ffmpeg — например, время
    кадра `t`, или `N-t` для обратного отсчёта (FR-02). Форматирование,
    округление и вычитание делаются внутри через целочисленную арифметику
    ffmpeg `floor`, чтобы на девятой секунде показывалось `00:01`, а не
    `00:00` (критерий A1).

    Секунды отрицательного значения не показываются: для countdown значение
    обрезается нулём на уровне выражения, а фаза hold (FR-03) добавляется
    отдельным фильтром в `filters.FilterBuilder.build_timer_filters()`.

    Инвариант: результат возвращается уже экранированным через
    :func:`_escape`, двоеточия внутри текста записаны как `\\:`.

    Args:
        value_expr: числовое выражение ffmpeg со значением таймера в секундах.
        fmt: формат из :data:`FORMATS`.

    Returns:
        Строку-выражение для `drawtext=text=...`, уже экранированную.

    Raises:
        VideoTimerError: `fmt: неизвестный формат часов` — если `fmt` не из
            :data:`FORMATS`; в v0.1 дополнительно принимается только `mmss`.

    Пример:
        clock_expression("t", "mmss")
        # "<выражение, печатающее 00:05 при t=5>"
    """
    raise NotImplementedError


# since: v0.1 (FR-04)
def static_clock_text(fmt: str) -> str:
    """Вернуть образец текста часов в заданном формате.

    Спека: FR-04. Версия: v0.1 (``mmss``), v0.2 (остальные форматы).

    Нужен там, где значение времени вычислить нельзя: подпись в GUI,
    ожидаемый кадр в тестах приёмки (A1, A2), текст в README.

    Args:
        fmt: формат из :data:`FORMATS`.

    Returns:
        Пример строки с нулями на месте цифр: ``00:00`` для ``mmss``.

    Raises:
        VideoTimerError: `fmt: неизвестный формат часов`.

    Пример:
        static_clock_text("mmss")
        # "00:00"
    """
    raise NotImplementedError
